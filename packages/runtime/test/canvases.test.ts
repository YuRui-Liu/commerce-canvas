import { afterEach, expect, it } from 'vitest';
import { mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { openDatabase } from '../src/db/open';
import { ProjectRepository } from '../src/projects/repository';
import { CanvasRepository } from '../src/canvases/repository';
import { AssetService } from '../src/assets/import';
const root = mkdtempSync(join(tmpdir(), 'commercecanvas-canvas-'));
let db = openDatabase(join(root, 'db.sqlite'));
afterEach(() => { db.close(); rmSync(root, { recursive: true, force: true }); });
it('persists graph/context and selection; rejects stale saves and foreign asset references atomically', async () => {
  const projects = new ProjectRepository(db);
  const a = projects.create('A'), b = projects.create('B');
  const service = new AssetService(db, root);
  const asset = await service.importText({ projectId: a.id, text: 'original version' });
  const foreign = await service.importText({ projectId: b.id, text: 'foreign version' });
  let repo = new CanvasRepository(db);
  const first = repo.create(a.id, 'First'), second = repo.create(a.id, 'Second');
  repo.select(a.id, first.document.id);
  const document = { ...first.document, nodes: [{ id: 'group', kind: 'group' as const, position: { x: 12, y: 20 } }, { id: 'node', kind: 'text' as const, assetVersionId: asset.id, parentId: 'group', stale: true, position: { x: 5, y: 6 } }], viewport: { x: 30, y: 80, zoom: 1.2 } };
  const panel = { ...first.panel, chatDraft: 'Keep the label', selectedIds: ['node'], inspectorDrafts: { node: 'pending text' } };
  const saved = repo.save(a.id, document, panel, 1);
  expect(saved.document.revision).toBe(2);
  expect(() => repo.save(a.id, document, panel, 1)).toThrow(/REVISION_CONFLICT/);
  expect(() => repo.load(b.id, first.document.id)).toThrow(/NOT_FOUND/);
  expect(() => repo.save(a.id, { ...saved.document, nodes: [{ id: 'bad', kind: 'asset', assetVersionId: foreign.id, position: { x: 0, y: 0 } }] }, panel, 2)).toThrow(/INVALID_REFERENCE/);
  expect(() => repo.save(a.id, { ...saved.document, projectId: b.id }, panel, 2)).toThrow(/INVALID_REFERENCE/);
  expect(db.prepare("SELECT version_id FROM asset_references WHERE owner_id=? AND kind='canvas'").all(first.document.id)).toEqual([{ version_id: asset.id }]);
  expect(projects.get(a.id)?.revision).toBe(1);
  expect(repo.load(a.id, first.document.id)).toEqual(saved);
  db.close(); db = openDatabase(join(root, 'db.sqlite')); repo = new CanvasRepository(db);
  expect(repo.load(a.id, first.document.id)).toEqual(saved);
  expect(repo.selected(a.id)).toBe(first.document.id);
  expect(repo.list(a.id).map(c => c.id)).toEqual([first.document.id, second.document.id]);
  expect(repo.list(b.id)).toEqual([]);
});
